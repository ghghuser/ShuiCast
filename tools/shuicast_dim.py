#!/usr/bin/env python3
"""
ShuiCast: slightly darker dialog background ("dim" theme), applied at build time.

  * dialog / static text / group box / check box backgrounds -> DIM_RGB
  * edit boxes and lists stay white, so input fields remain easy to read
  * text stays black (no real dark mode: tab headers, buttons and the title bar
    keep the standard Windows look)

Change the colour by editing DIM_RGB below (255 = white, 240 = standard dialog
grey, lower = darker).

Usage:  python shuicast_dim.py <path to the "trunk" folder>

Idempotent, and fails loudly if an anchor cannot be found.
"""
import re
import sys
from pathlib import Path

DIM_RGB = (218, 218, 218)

APP = Path(sys.argv[1] if len(sys.argv) > 1 else "trunk") / "shuicast"

HEADER = """#pragma once

// Slightly darker dialog background (generated by tools/shuicast_dim.py)
#define SHUICAST_DIM_COLOR RGB(%d, %d, %d)

inline HBRUSH ShuiCastDimCtlColor( CDC *pDC, UINT nCtlColor, HBRUSH defaultBrush )
{
	static CBrush dimBrush( SHUICAST_DIM_COLOR );

	switch ( nCtlColor )
	{
	case CTLCOLOR_DLG:
	case CTLCOLOR_STATIC:
	case CTLCOLOR_BTN:
		pDC->SetBkColor( SHUICAST_DIM_COLOR );
		return (HBRUSH)dimBrush.GetSafeHandle();
	}
	return defaultBrush;
}
""" % DIM_RGB

# (cpp, header, class)  -- dialogs that have no WM_CTLCOLOR handler yet
NEW_HANDLER = [
    ("MainWindow", "CMainWindow"),
    ("Config", "CConfig"),
    ("About", "CAbout"),
    ("EditMetadata", "CEditMetadata"),
    ("FindWindow", "CFindWindow"),
]
# tab pages that already return a (white) brush for everything
OLD_HANDLER = [
    ("BasicSettings", "CBasicSettings"),
    ("YPSettings", "CYPSettings"),
    ("AdvancedSettings", "CAdvancedSettings"),
]


def fail(msg):
    print("shuicast_dim: ERROR: " + msg, file=sys.stderr)
    sys.exit(1)


def sub_once(text, pattern, repl, label, flags=0):
    new, n = re.subn(pattern, repl, text, count=0, flags=flags)
    if n != 1:
        fail("%s: expected exactly 1 match, found %d" % (label, n))
    return new


def patch_file(name, func):
    path = APP / name
    if not path.exists():
        fail("%s not found" % path)
    raw = path.read_bytes()
    crlf = b"\r\n" in raw
    text = raw.decode("latin-1").replace("\r\n", "\n")
    if "shuicastdim" in text.lower():
        print("shuicast_dim: %s already patched, skipped" % name)
        return
    text = func(text)
    if crlf:
        text = text.replace("\n", "\r\n")
    path.write_bytes(text.encode("latin-1"))
    print("shuicast_dim: patched %s" % name)


def add_include(t, label):
    return sub_once(
        t,
        r'(#include "stdafx\.h"\n)',
        lambda m: m.group(1) + '#include "DimTheme.h"\n',
        label + " include",
        re.I,
    )


def make_old(cls):
    def f(t):
        t = add_include(t, cls)
        return sub_once(
            t,
            r"(HBRUSH %s::OnCtlColor\(CDC\* pDC, CWnd\* pWnd, UINT nCtlColor\)\s*\{\s*)return m_brush;" % cls,
            lambda m: m.group(1) + "return ShuiCastDimCtlColor( pDC, nCtlColor, m_brush );",
            cls + " OnCtlColor",
        )
    return f


def make_new_cpp(cls):
    def f(t):
        t = add_include(t, cls)
        handler = (
            "HBRUSH %s::OnCtlColor(CDC* pDC, CWnd* pWnd, UINT nCtlColor)\n"
            "{\n"
            "\treturn ShuiCastDimCtlColor( pDC, nCtlColor, CDialog::OnCtlColor( pDC, pWnd, nCtlColor ) );\n"
            "}\n\n" % cls
        )
        return sub_once(
            t,
            r"(BEGIN_MESSAGE_MAP\s*\(\s*%s\s*,\s*CDialog\s*\)\n)" % cls,
            lambda m: handler + m.group(1) + "\tON_WM_CTLCOLOR()\n",
            cls + " message map",
        )
    return f


def new_h(cls):
    def f(t):
        return sub_once(
            t,
            r"\n([ \t]*DECLARE_MESSAGE_MAP\(\))",
            lambda m: "\n\tafx_msg HBRUSH OnCtlColor(CDC* pDC, CWnd* pWnd, UINT nCtlColor);  // ShuiCastDim\n" + m.group(1),
            cls + " header",
        )
    return f


# header file
hp = APP / "DimTheme.h"
if hp.exists():
    print("shuicast_dim: DimTheme.h already exists, skipped")
else:
    hp.write_bytes(HEADER.replace("\n", "\r\n").encode("ascii"))
    print("shuicast_dim: created DimTheme.h")

for base, cls in OLD_HANDLER:
    patch_file(base + ".cpp", make_old(cls))
for base, cls in NEW_HANDLER:
    patch_file(base + ".cpp", make_new_cpp(cls))
    patch_file(base + ".h", new_h(cls))
print("shuicast_dim: done")
